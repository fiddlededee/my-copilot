#!/bin/bash

# Script to automatically generate README documentation for Windows and Ubuntu
# This script creates separate documentation files for each platform

set -e  # Exit on error

pushd doc

# Check for publishing prompt
echo "Writing check for publishing prompt..."

cat > /home/nmp/work/git/al/my-copilot/doc/prepare-for-publishing-checklist-query.md << 'EOF'
Your task is to check, using a checklist, whether the current version of the copilot `copilot-v2.main.kts` is ready for publication:

1. The current version is higher than the one on GitHub (https://raw.githubusercontent.com/fiddlededee/my-copilot/refs/heads/main/copilot-v2.main.kts)
2. All current models point to Kodik Router (not Dashscope)
3. All tools are uncommented, except the tool for running scripts in Docker
4. There are no comments generated by an LLM during coding
5. No local paths exist in a script
6. There are no crude debugging artifacts (if they are commented out, that is OK)
7. Copilot uses my-copilot-models/build.gradle.kts that are really published on Maven Central
8. Copilot uses latest published version
9. Copilot version is equal or higher than my-copilot-models version
10. Release hints point to current version

Also generate a description of what has changed in the current version relative to the previous one. Divide all changes into the following categories: key changes, other changes, minor improvements. Ignore minor improvements.

Give to the changes section an id `#changes` so that GitHub would render it correctly: {#changes}

To accomplish this task, read the contents of the script from GitHub and from the project. Note that you can read from GitHub using the pre-written script tool. When reading the script from the project, set the initial limit to 100000.

Do not use any more tools.

End with a summary: Ready / Not ready; if not ready, state what isn’t; then, in 1–2 short sentences, say what changed
EOF

echo "Starting documentation generation process..."

# Step 1: Create README-OPENIDE-WINDOWS.md with the first prompt
echo "Creating README-OPENIDE-WINDOWS.md..."

cat > README-OPENIDE-WINDOWS.md << 'EOF'
Your role is IT professional.

What is this script for
copilot-v2.main.kts

I need the essence (in 2-3 short paragraphs)

To render answer for this and further questions read the whole file (limit -- 100000) and be especially attentive at Doc hint comments

EOF

# Step 2: Run copilot for Windows documentation
echo "Running copilot for Windows documentation..."
kotlin ../copilot-v2.main.kts README-OPENIDE-WINDOWS.md

# Step 3: Copy to Ubuntu version
echo "Creating README-OPENIDE-UBUNTU.md..."
cp README-OPENIDE-WINDOWS.md README-OPENIDE-UBUNTU.md

# Step 4: Add Windows-specific prompt to README-OPENIDE-WINDOWS.md
echo "Adding Windows-specific prompt..."

cat >> README-OPENIDE-WINDOWS.md << 'EOF'

Draft a compact how to start guide for me, If I need to set up it in Windows and OpenIDE

Suppose I need to use it in my `D:\my-projects\my-some-great-project`

Use your knowledge, internet search and read the whole file, don't read any other files or directories

The start guide should contain information on Kotlin, Java and OS version
with which this documentation was built (since it is build with the
same copilot)
EOF

# Step 5: Add Ubuntu-specific prompt to README-OPENIDE-UBUNTU.md
echo "Adding Ubuntu-specific prompt..."

cat >> README-OPENIDE-UBUNTU.md << 'EOF'

Draft a compact how to start guide for me, If I need to set up it in Ubuntu and OpenIDE

Suppose I need to use it in my `~/my-projects/my-some-great-project`

Use your knowledge, internet search and read the whole file, don't read any other files or directories

The start guide should contain information on Kotlin, Java and OS version
with which this documentation was built (since it is build with the
same copilot)
EOF

kotlin ../copilot-v2.main.kts README-OPENIDE-WINDOWS.md &
kotlin ../copilot-v2.main.kts README-OPENIDE-UBUNTU.md &
kotlin ../copilot-v2.main.kts prepare-for-publishing-checklist-query.md &
wait

popd